def sha256_and_size(path: Path) -> tuple[str | None, int | None, str | None]:
    """Return (digest, bytes, error). Never raises: an unreadable file is coverage data."""
    digest = hashlib.sha256()
    total = 0
    try:
        with path.open("rb") as handle:
            while chunk := handle.read(131_072):
                digest.update(chunk)
                total += len(chunk)
    except OSError as error:
        return None, None, str(error)
    return digest.hexdigest(), total, None


def media_type_for(suffix: str) -> str:
    for name, suffixes in MEDIA_TYPES.items():
        if suffix in suffixes:
            return name
    if suffix in SOURCE_SUFFIXES:
        return "source"
    return "other"


def walk_project(root: Path) -> tuple[list[Path], list[str]]:
    """Collect reviewable files under the project, plus notes on what was left out.

    Everything outside the allowlist is reported rather than dropped silently, so a
    reader can tell the difference between "nothing to review there" and "not looked at".
    """
    files: list[Path] = []

    content_root = root / CONTENT_TREE
    for path in sorted(content_root.rglob("*")) if content_root.is_dir() else []:
        if any(part in SKIP_DIRECTORIES for part in path.relative_to(root).parts):
            continue
        if path.is_dir() or path.name.startswith("."):
            continue
        if path.suffix.lower() in IGNORED_SUFFIXES:
            continue
        files.append(path)

    for path in sorted(root.glob("*")):
        if path.is_file() and (path.name in ROOT_FILE_NAMES or path.suffix in ROOT_FILE_SUFFIXES):
            files.append(path)

    reviewed = {CONTENT_TREE, PACKAGES_TREE} | ROOT_FILE_NAMES | KNOWN_GENERATED_TREES
    skipped = sorted(
        f"{entry.name}{'/' if entry.is_dir() else ''}"
        for entry in root.glob("*")
        if entry.name not in reviewed
        and entry.suffix not in ROOT_FILE_SUFFIXES
        and entry.suffix.lower() not in IGNORED_SUFFIXES
        and not entry.name.startswith(".")
    )
    return files, skipped


def scan_signals(sources: list[tuple[str, str]]) -> dict[str, Any]:
    """Match every signal against every source file, recording where each one fired."""
    compiled = {name: re.compile(spec["pattern"], re.IGNORECASE) for name, spec in SIGNALS.items()}
    hits: dict[str, list[dict[str, Any]]] = {name: [] for name in SIGNALS}
    counts: dict[str, int] = {name: 0 for name in SIGNALS}
    truncated: set[str] = set()

    for relative_path, text in sources:
        for line_number, line in enumerate(text.splitlines(), 1):
            stripped = line.strip()
            if not stripped or stripped.startswith(("//", "*", "/*")):
                # Comments describe intent, not behaviour. Skipping them is what keeps
                # a doc comment mentioning "enemy" from being read as a mechanic.
                continue
            for name, pattern in compiled.items():
                match = pattern.search(stripped)
                if not match:
                    continue
                counts[name] += 1
                if len(hits[name]) >= MAX_EVIDENCE_PER_SIGNAL:
                    truncated.add(name)
                    continue
                hits[name].append(
                    {
                        "file": relative_path,
                        "line": line_number,
                        "match": match.group(0),
                        "text": stripped[:160],
                    }
                )

    return {
        name: {
            "present": bool(hits[name]),
            "informs": SIGNALS[name]["informs"],
            "note": SIGNALS[name]["note"],
            "occurrences": counts[name],
            "evidenceTruncated": name in truncated,
            "evidence": hits[name],
        }
        for name in SIGNALS
    }


def collect(root: Path) -> dict[str, Any]:
    project_files = list(root.glob("*.esproj"))
    files, skipped = walk_project(root)

    assets: list[dict[str, Any]] = []
    manifest: list[dict[str, Any]] = []
    sources: list[tuple[str, str]] = []
    unreadable: list[dict[str, str]] = []
    oversized: list[str] = []

    for path in files:
        relative = str(path.relative_to(root))
        suffix = path.suffix.lower()
        kind = media_type_for(suffix)
        digest, size, error = sha256_and_size(path)
        if error is not None:
            unreadable.append({"id": relative, "error": error})
            continue

        manifest.append(
            {"id": relative, "role": kind, "type": suffix.lstrip(".") or "none", "sha256": digest, "bytes": size}
        )

        if kind == "source":
            if size is not None and size > MAX_SOURCE_BYTES:
                oversized.append(relative)
                continue
            try:
                sources.append((relative, path.read_text(errors="replace")))
            except OSError as error:
                unreadable.append({"id": relative, "error": str(error)})
        elif kind in {"image", "video", "audio", "model3d"}:
            assets.append(
                {
                    "assetId": f"project_asset:{relative}",
                    "role": "project_image_asset" if kind == "image" else f"project_{kind}_asset",
                    "mediaType": kind,
                    "fileName": path.name,
                    "path": str(path),
                    "sha256": digest,
                    "bytes": size,
                    "status": "available",
                }
            )

    packages = sorted(entry.name for entry in (root / "Packages").glob("*") if entry.suffix in {".lspkg", ".lsc"})

    signals = scan_signals(sources)
    coverage: list[str] = []
    if unreadable:
        coverage.append(f"{len(unreadable)} file(s) could not be read")
    if oversized:
        coverage.append(f"{len(oversized)} source file(s) over {MAX_SOURCE_BYTES // 1024} KB were not scanned")
    truncated = sorted(name for name, value in signals.items() if value["evidenceTruncated"])
    if truncated:
        coverage.append(f"evidence capped at {MAX_EVIDENCE_PER_SIGNAL} per signal for: {', '.join(truncated)}")
    if skipped:
        coverage.append(f"not reviewed (outside {CONTENT_TREE}/): {', '.join(skipped)}")

    return {
        "status": "REVIEW_INPUT_READY",
        "stage": "review_input",
        "collectorVersion": COLLECTOR_VERSION,
        "projectPath": str(project_files[0]) if project_files else None,
        "counts": {
            "filesInspected": len(manifest),
            "sourceFilesScanned": len(sources),
            "mediaAssets": len(assets),
            "packages": len(packages),
        },
        "installedPackages": packages,
        "signals": signals,
        "assets": assets,
        "manifest": sorted(manifest, key=lambda entry: entry["id"]),
        "coverage": coverage,
        "unreadable": unreadable,
        "oversizedSources": oversized,
        "skippedTrees": skipped,
    }


def write_private_json(path: Path, value: dict[str, Any]) -> None:
    """Atomically persist review evidence with owner-only permissions."""

    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{secrets.token_hex(8)}.tmp")
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as output:
            output.write(json.dumps(value, sort_keys=True))
            output.write("\n")
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
        path.chmod(0o600)
    finally:
        temporary.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--project", required=True, help="Path to the .esproj or its directory.")
    parser.add_argument("--signals-only", action="store_true", help="Omit the per-file manifest.")
    parser.add_argument("--output", help="Persist the complete result to this path and print only its reference.")
    args = parser.parse_args()

    target = Path(args.project).expanduser()
    root = target.parent if target.suffix == ".esproj" else target
    if not root.is_dir():
        print(
            json.dumps(
                {
                    "status": "FAILED",
                    "stage": "review_input",
                    "reason": "project_not_found",
                    "message": f"{root} is not a directory",
                },
                sort_keys=True,
            )
        )
        return 1

    result = collect(root)
    if args.signals_only:
        result.pop("manifest", None)
        result.pop("assets", None)
    if args.output:
        output_path = Path(args.output).expanduser().resolve()
        write_private_json(output_path, result)
        print(
            json.dumps(
                {
                    "status": "REVIEW_INPUT_STORED",
                    "stage": "review_input",
                    "collectorVersion": result["collectorVersion"],
                    "reviewInputPath": str(output_path),
                    "reviewSummary": {
                        key: result[key]
                        for key in (
                            "counts",
                            "installedPackages",
                            "signals",
                            "assets",
                            "coverage",
                            "unreadable",
                            "oversizedSources",
                            "skippedTrees",
                        )
                    },
                },
                sort_keys=True,
            )
        )
    else:
        print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
